-- LabQueue: начальная схема (представление SDD 005). Время хранится в UTC.
-- Скрипт совместим с PostgreSQL 16 и H2 (режим PostgreSQL) для тестов.

CREATE TABLE study_group (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number VARCHAR(16) NOT NULL UNIQUE
);

CREATE TABLE app_user (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email            VARCHAR(254) NOT NULL UNIQUE,
    password_hash    VARCHAR(100),
    full_name        VARCHAR(150) NOT NULL,
    role             VARCHAR(16)  NOT NULL CHECK (role IN ('STUDENT', 'TEACHER', 'ADMIN')),
    group_id         BIGINT REFERENCES study_group (id),
    email_verified   BOOLEAN      NOT NULL DEFAULT FALSE,
    failed_attempts  INTEGER      NOT NULL DEFAULT 0,
    locked_until     TIMESTAMP WITH TIME ZONE,
    token            VARCHAR(64) UNIQUE,
    token_expires_at TIMESTAMP WITH TIME ZONE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT student_has_group CHECK (role <> 'STUDENT' OR group_id IS NOT NULL)
);

CREATE TABLE discipline (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(150) NOT NULL,
    lab_count  INTEGER      NOT NULL CHECK (lab_count BETWEEN 1 AND 15),
    teacher_id BIGINT       NOT NULL REFERENCES app_user (id)
);

CREATE TABLE discipline_group (
    discipline_id BIGINT NOT NULL REFERENCES discipline (id),
    group_id      BIGINT NOT NULL REFERENCES study_group (id),
    PRIMARY KEY (discipline_id, group_id)
);

CREATE TABLE slot (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discipline_id   BIGINT       NOT NULL REFERENCES discipline (id),
    teacher_id      BIGINT       NOT NULL REFERENCES app_user (id),
    starts_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    place           VARCHAR(200) NOT NULL,
    defense_minutes INTEGER      NOT NULL,
    capacity        INTEGER      NOT NULL,
    status          VARCHAR(16)  NOT NULL CHECK (status IN ('PLANNED', 'IN_PROGRESS', 'FINISHED', 'CANCELLED')),
    cancel_reason   VARCHAR(500),
    version         INTEGER      NOT NULL DEFAULT 0,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT slot_interval CHECK (ends_at > starts_at),
    CONSTRAINT slot_defense CHECK (defense_minutes BETWEEN 5 AND 30)
);

CREATE INDEX slot_teacher_time ON slot (teacher_id, starts_at);

CREATE TABLE slot_group (
    slot_id  BIGINT NOT NULL REFERENCES slot (id),
    group_id BIGINT NOT NULL REFERENCES study_group (id),
    PRIMARY KEY (slot_id, group_id)
);

CREATE TABLE booking (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_id       BIGINT      NOT NULL REFERENCES slot (id),
    student_id    BIGINT      NOT NULL REFERENCES app_user (id),
    lab_number    INTEGER     NOT NULL CHECK (lab_number BETWEEN 1 AND 15),
    status        VARCHAR(16) NOT NULL CHECK (status IN ('WAITLISTED', 'BOOKED', 'IN_QUEUE', 'DEFENDING',
                                                         'PASSED', 'REWORK', 'NO_SHOW', 'CANCELLED', 'EXPIRED')),
    position      INTEGER,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    called_at     TIMESTAMP WITH TIME ZONE,
    noshow_ack_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX booking_slot ON booking (slot_id, status);
CREATE INDEX booking_student ON booking (student_id);

CREATE TABLE journal_entry (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    actor   VARCHAR(254) NOT NULL,
    action  VARCHAR(40)  NOT NULL,
    details VARCHAR(500)
);
